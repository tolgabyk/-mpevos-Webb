let currentLanguage = 'tr';

/**
 * Switch all page content to the specified language
 */
function setLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem('impevos-lang', lang);
  document.documentElement.lang = lang;

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
        element.placeholder = translations[lang][key];
      } else {
        element.innerHTML = translations[lang][key];
      }
    }
  });

  // Update active language button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Update page title
  document.title = lang === 'tr'
    ? 'IMPEVOS | Teknoloji & İnovasyon'
    : 'IMPEVOS | Technology & Innovation';

  // Update meta description
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) {
    metaDesc.content = lang === 'tr'
      ? 'IMPEVOS - Yapay zeka, yazılım geliştirme ve otomasyon çözümleriyle geleceğin teknolojisini bugün inşa ediyoruz.'
      : 'IMPEVOS - Building tomorrow\'s technology today with AI, software development, and automation solutions.';
  }
}

function getCurrentLanguage() {
  return currentLanguage;
}

/**
 * Initialize i18n — loads saved language or defaults to Turkish
 */
function initI18n() {
  const savedLang = localStorage.getItem('impevos-lang') || 'tr';
  setLanguage(savedLang);
}
